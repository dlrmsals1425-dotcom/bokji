/**
 * 복지 외 분야(산업·농림) 분류 — 기본 결과에서 숨기고 필터로만 보여 준다 (운영자 결정 2026-10-02).
 *  - agri: 농림축산어업 생산·경영 지원 (농기계·비료·종자·방제·축사·사료·재해보험·직불금·영농정착 등)
 *  - business: 소상공인·기업·법인·창업 등 사업체 자격으로 받는 지원 (창업·경영·시설·운영자금, 판로·마케팅, 인증, 박람회, 고용장려금 등)
 * 사람(개인·가구)에게 돌아가는 복지성 혜택은 숨기지 않는다:
 *   농어업인 안전(재해)보험·건강검진·복지(행복)바우처·공익수당·출산·노후·주거 지원,
 *   1인 자영업자 유급병가·고용/산재보험료·노란우산공제·출산급여·자녀 돌봄 등 (운영자 방향 2026-10-02).
 */
export type Sector = "agri" | "business";

const AGRI_NAME = /(농업인|농업경영|농가|어업인|어가|어선|축산|가축|양봉|양식|영농|임업|산림경영|임산물|귀농|귀어|귀산촌|농기계|농업기계|비료|퇴비|종자(?!통장)|종묘|육묘|묘판|상토|농약|병해충|(?<!해충\s?)방제|농산물|수산물|친환경농|농지|과수|과원|원예|시설하우스|비닐하우스|하우스\s*(?:수정벌|시설|신축)|스마트팜|축사|사료|낚시어선|수산|해녀|어촌계|직불금|직접지불|한우|젖소|낙농|착유|양돈|양계|산란계|육계|흑염소|꿀벌|수정벌|벼\s|벼$|^벼|딸기|농작물|농자재|농업자재|폐비닐|공동방제|농어촌민박|관광농원|농촌융복합|조림|임도|산주)/;
const AGRI_TARGET = /(농업인|농업경영체|농가|어업인|어가|축산|임업인|영농|어선|양식업|농어업인|농업법인|사육|재배|착유|생산자단체|산림\s*소유|산주)/;
/** 농림 분야로 분류돼도 사람에게 돌아가는 생활 지원이면 숨기지 않는다 */
const PERSONAL_WELFARE = /(건강\s*검진|특수\s*검진|안전\s*(?:재해\s*)?보험|안전재해보험|복지바우처|행복\s*바우처|(?:농|어|농어)업인\s*(?:바우처|생생카드|행복이용권|이용권)|생생카드|행복이용권|영농도우미|농가도우미|영농작업비|출산|결혼\s*(?:공제|장려|지원금|축하)|행복결혼|대학생|자녀|장학|돌봄|의료|상해|연금|노후\s*(?:생활|소득|대비|연금)|요양|닥터|원격진료|청소년|노인|어르신|장애인|취약|생활안정|(?:농민|농어민|농업인|어업인|임업인|농어업인)\s*(?:공익\s*)?수당|공익수당|주택\s*(?:수리|구입|신축|임차|개량)|주거비|펫|반려|왕진|진료|교통|통학)/;
/** 사람 대상 표현이 앞에 오면(농촌 어르신·주민 등) 농림 종사자 대상이 아니다 */
const RESIDENT_TARGET = /(주민|거주하는|거주자|노인|어르신|장애인|저소득|취약|학생|아동|임산부|출산|청년|구직|미취업|근로자)/;
/** 사람 대상 표현이 있어도 생산 지원이 분명한 이름 (가축 진료, 노후 어선·하우스 교체, 창업·영농정착 등) */
const PRODUCTION_STRONG = /(창업|영농\s*(?:보조|정착|기반)|농기계|농업기계|노후\s*기관|하우스|가축|양축|사육|축산|한우|젖소|어선(?!원)|농작물|사료|비료)/;

const BIZ_NAME = /(소상공인|자영업|사업자|창업|점포|상가|(?<!직)(?<!이사)업체|기업\s*(지원|육성|인증|유치|바우처)|중소기업\s*(지원|육성|경영|박람회|매출)|수출|판로|마케팅|경영\s*(안정|개선|컨설팅)|경영자금|운영자금|시설자금|창업자금|육성자금|정책자금|전통시장|상인|가맹점|프랜차이즈|입주기업|벤처|스타트업|특허|기술\s*개발|R&D|사회적경제기업|협동조합\s*(육성|지원)|박람회\s*참가|전시회\s*참가|HACCP|매출채권|팩토링|브랜드택시|콘텐츠\s*제작|고용촉진장려금|고용장려금|채용\s*장려금|협력약국)/;
/** 사업자 관련어가 있어도 사람에게 돌아가는 혜택 (근로자·구직자·가구·개인 복지) */
const BIZ_EXEMPT = /(취업|취[·∙‧ ]*창업|재직|근속|주택|복지|장학|학생|저소득|서민|가구|가정|효도|숙소|구직|근로자|노동자|일자리|직원|재직자|청년\s*(월세|전세|주거)|전월세|생계|긴급|폐업\s*(소상공인|자영업자)?\s*(재취업|생활)|고용보험|산재보험|사회보험|두루누리|출산|육아|자녀|유급\s*병가|병가|상병|건강\s*검진|노란우산|돌봄|휴가|의료|심리|이사비|퇴직자)/;
const BIZ_TARGET_START = /^\s*[-·○◦*]?\s*(?:지원\s*대상\s*:\s*)?(소상공인|중소기업|중소·중견기업|기업|법인|사업자|자영업자|창업기업|예비창업자|개인사업자|도내\s*기업|관내\s*기업|관내\s*소상공인|택시\s*운송사업자|[가-힣]+시\s*콘텐츠기업|『?중소기업기본법』?\s*상의\s*중소기업|도내\s*[가-힣]*\s*채용기업)/;

export interface SectorInput {
  name: string;
  target?: string;
  gov24Field?: string;
  users?: string;
}

export function classifySector(x: SectorInput): Sector | undefined {
  const name = x.name;
  const target = (x.target ?? "").slice(0, 160);
  const personal = (PERSONAL_WELFARE.test(name) && !PRODUCTION_STRONG.test(name)) || /(시민|구민|군민|도민)\s*(?:생활)?\s*안전\s*보험/.test(name);
  if (x.gov24Field === "농림축산어업" && !personal) return "agri";
  if (!personal) {
    if (AGRI_NAME.test(name)) return "agri";
    // 대상 문구 앞부분이 농가·농업인 등 생산 주체이고, 일반 주민·어르신 같은 사람 대상 표현이 없으면 농림 생산 지원
    const head = target.slice(0, 60);
    if (AGRI_TARGET.test(head) && !RESIDENT_TARGET.test(head)) return "agri";
  }
  if (BIZ_EXEMPT.test(name)) return undefined;
  if (BIZ_NAME.test(name)) return "business";
  if (BIZ_TARGET_START.test(target)) return "business";
  if (x.users && /소상공인|법인/.test(x.users) && !/개인|가구/.test(x.users)) return "business";
  return undefined;
}
